// Generates src/api/schema.d.ts from the API's OpenAPI document (src/Illiria.Api/openapi/illiria.json).
import { readFile, writeFile } from "node:fs/promises"
import openapiTS, { astToString } from "openapi-typescript"

const source = new URL("../../src/Illiria.Api/openapi/illiria.json", import.meta.url)
const target = new URL("../src/api/schema.d.ts", import.meta.url)

const document = JSON.parse(await readFile(source, "utf8"))
const header = "// Generated by `pnpm run api:types` from src/Illiria.Api/openapi/illiria.json. Do not edit.\n\n"
await writeFile(target, header + astToString(await openapiTS(document)))
console.log(`Wrote ${target.pathname}`)
